"""Generate one mp3 per question + word timings (audio/timings.js) with edge-tts.

Usage (from the lahja folder):  python3 tools/make_audio.py
Replace any audio/qN.mp3 with a real recording afterwards if you like:
the game then spreads the karaoke highlight evenly over the recording.
"""
import asyncio, json, os, re, subprocess
import edge_tts
import edge_tts.communicate as _ec

# Behind a TLS-inspecting proxy, point SSL_CERT_FILE at its CA bundle.
if os.environ.get("SSL_CERT_FILE"):
    import ssl
    _ec._SSL_CTX = ssl.create_default_context(cafile=os.environ["SSL_CERT_FILE"])

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load_questions():
    src = open(os.path.join(ROOT, "questions.js"), encoding="utf-8").read()
    js = "const window={};" + src + ";console.log(JSON.stringify(window.LAHJA_QUESTIONS))"
    return json.loads(subprocess.check_output(["node", "-e", js]))

async def one(q):
    comm = edge_tts.Communicate(q["text"], q["voice"], rate="-8%", boundary="WordBoundary")
    words, path = [], os.path.join(ROOT, "audio", q["id"] + ".mp3")
    with open(path, "wb") as f:
        async for chunk in comm.stream():
            if chunk["type"] == "audio":
                f.write(chunk["data"])
            elif chunk["type"] == "WordBoundary":
                words.append([round(chunk["offset"] / 1e7, 3),
                              round((chunk["offset"] + chunk["duration"]) / 1e7, 3),
                              chunk["text"]])
    return q["id"], words

async def main():
    out = {}
    for q in load_questions():
        qid, words = await one(q)
        out[qid] = words
        print(qid, len(words), "words", q["text"].split().__len__(), "tokens")
    with open(os.path.join(ROOT, "audio", "timings.js"), "w", encoding="utf-8") as f:
        f.write("// generated by tools/make_audio.py\nwindow.LAHJA_TIMINGS = ")
        json.dump(out, f, ensure_ascii=False)
        f.write(";\n")

asyncio.run(main())
