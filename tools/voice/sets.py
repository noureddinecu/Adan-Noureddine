#!/usr/bin/env python3
"""Splits the question arsenal (tools/voice/arsenal.json: [difficulty 1..4, truth, text, correction]) into 10 groups
for «صح أم خطأ» → web/js/tf-sets.js. Each group gets its share of easy (1), medium (2) and hard (3–4) questions;
no question is in two groups. usage: python3 tools/voice/sets.py [groups=10]"""
import json, os, random, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
N = int(sys.argv[1]) if len(sys.argv) > 1 else 10
items = json.load(open(os.path.join(ROOT, 'tools', 'voice', 'arsenal.json'), encoding='utf-8'))
rng = random.Random(2026)
sets = [[[], [], []] for _ in range(N)]
for stage, levels in enumerate(((1,), (2,), (3, 4))):
    for lv in levels:                       # deal level by level so the hardest ones are spread too
        pool = [x for x in items if x[0] == lv]; rng.shuffle(pool)
        # balance true / false inside every group: alternate true and false items while dealing
        t = [x for x in pool if x[1]]; f = [x for x in pool if not x[1]]; mix = []
        while t or f:
            if t: mix.append(t.pop())
            if f: mix.append(f.pop())
        start = sum(len(s[stage]) for s in sets)  # continue the deal where the previous level stopped
        for k, x in enumerate(mix): sets[(start + k) % N][stage].append(x)
with open(os.path.join(ROOT, 'web', 'js', 'tf-sets.js'), 'w', encoding='utf-8') as fo:
    fo.write('/* «صح أم خطأ» — the questions in %d groups (generated by tools/voice/sets.py from tools/voice/arsenal.json).\n'
             ' * TF_SETS[group] = [easy[], medium[], hard[]]; item: [difficulty 1..4, true|false, statement, correction].\n'
             ' * Written statements stay WITHOUT diacritics. */\nwindow.TF_SETS = [\n' % N)
    fo.write(',\n'.join(json.dumps(s, ensure_ascii=False) for s in sets))
    fo.write('\n];\n')
for i, s in enumerate(sets): print(i + 1, [len(x) for x in s], 'hard≥4:', sum(1 for x in s[2] if x[0] >= 4))
